/** Surfaces that exist for the compiler or the physics only and are never drawn. */
inline bool IsNoDrawFlags(int flags)
{
	return (flags & (SURF_NODRAW | SURF_SKIP | SURF_HINT | SURF_TRIGGER)) != 0;
}

